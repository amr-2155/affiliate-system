/** يعيد الملف التسويقي المناسب لفئة المنتج الحقيقي (يُستخدم في الخطة والتحليل). */
export function detectProfile(product: ProductProfile): { profile: CategoryProfile; key: string } {
  const catNameAr = product.category?.nameAr || ""
  const catName = (product.category?.name || "").toLowerCase()
  const nameAr = product.nameAr || ""
  const description = `${product.descriptionAr || ""} ${product.description || ""}`.toLowerCase()

  const keywordMap: [RegExp, string][] = [
    [/إلكترون|موبايل|هاتف|كمبيوتر|لابتوب|سماعة|شاشة|شاحن|ساعة ذكية/i, "electronics"],
    [/جمال|عناية|عطر|مكياج|بشرة|شعر|skincare|beauty|cosmetic/i, "beauty"],
    [/ملابس|موضة|جينز|تيشيرت|حذاء|فستان|قميص|كوتشي|أزياء/i, "clothing"],
    [/منزل|مطبخ|أجهزة|مكنسة|طقم|أواني|مفروشات|home|kitchen/i, "home"],
    [/رياض|جيم|لياقة|تريند|تمارين|عدة رياضية|sport|gym|fitness/i, "sports"],
    [/لعب|أطفال|دمية|توك توك|لعبة|مكعبات|toys|kids/i, "toys"],
    [/كتاب|قراءة|مؤلف|رواية|راوية/i, "books"],
    [/سيارة|موتور|كاوتش|زيت محرك|كماليات سيارة|car|auto/i, "automotive"],
  ]

  for (const [re, key] of keywordMap) {
    if (re.test(catNameAr) || re.test(catName) || re.test(nameAr) || re.test(description)) {
      return { profile: PROFILES[key], key }
    }
  }
  return { profile: DEFAULT_PROFILE, key: "default" }
}

function rotate<T>(arr: T[], seed: number): T[] {
  if (arr.length === 0) return arr
  const offset = Math.abs(seed) % arr.length
  return [...arr.slice(offset), ...arr.slice(0, offset)]
}

function buildSellingPoints(product: ProductProfile, price: number, commission: number, deliveryInfo: string): string[] {
  const points = [
    `السعر ${formatCurrency(price)} بجودة حقيقية تنافس الأسواق.`,
    `عمولتك ${formatCurrency(commission)} على كل وحدة تُسلَّم — مناسبة للاستثمار في الإعلانات.`,
  ]
  if ((product.stock || 0) > 0) points.push(`المنتج متوفر حالياً بالمخزون — اذكر حالة التوفر الحقيقية كما هي في صفحة المنتج.`)
  if (product.category?.nameAr) points.push(`من فئة «${product.category.nameAr}» — فئة عالية الطلب على الإنترنت.`)
  points.push(deliveryInfo)
  if (product.image) points.push(`صور جاهزة عالية الجودة يمكن استخدامها في الإعلانات والفيديوهات.`)
  return points
}

