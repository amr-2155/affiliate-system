export function strategyToText(s: GeneratedStrategy): string {
  const lines: string[] = []
  lines.push(`${s.title}`)
  lines.push(
    `المنتج: ${s.product.nameAr} | السعر: ${formatCurrency(s.product.price)} | عمولة الوحدة: ${formatCurrency(s.product.commission)}`
  )
  lines.push("")
  for (const sec of s.sections) {
    lines.push(`${sec.emoji} ${sec.title}`)
    for (const item of sec.items) {
      if (typeof item === "string") lines.push(`• ${item}`)
      else lines.push(`• ${item.question}\n  ↳ ${item.answer}`)
    }
    lines.push("")
  }
  return lines.join("\n")
}
